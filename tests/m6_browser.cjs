"use strict";
const {chromium}=require("playwright");
const assert=require("node:assert/strict");
let raw="";
process.stdin.setEncoding("utf8"); process.stdin.on("data",part=>raw+=part);
process.stdin.on("end",async()=>{
  const input=JSON.parse(raw), browser=await chromium.launch({headless:true,channel:process.env.NEXUS_TEST_BROWSER_CHANNEL || "msedge"});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[];
  page.on("pageerror",error=>errors.push(error.message));
  try {
    await page.goto(input.origin); await page.locator("#token").fill(input.token); await page.locator('#login-form button[type="submit"]').click();
    await page.locator("#console").waitFor({state:"visible"});
    await page.locator('[data-tab="memories"]').click();
    await page.locator("#project-name").fill("M6 演示"); await page.locator('#project-form button[type="submit"]').click();
    await page.waitForFunction(()=>[...document.querySelector("#chat-project").options].some(n=>n.textContent==="M6 演示"));
    await page.locator('[data-tab="chat"]').click(); await page.locator("#chat-project").selectOption({label:"M6 演示"}); await page.locator("#chat-new").click();
    await page.waitForFunction(()=>!document.querySelector("#chat-send").disabled);
    await page.locator("#chat-tools").uncheck(); await page.locator("#chat-text").fill("讨论小游戏项目"); await page.locator("#chat-send").click();
    await page.waitForFunction(()=>document.querySelectorAll(".chat-turn").length===1 && !document.querySelector("#chat-send").disabled);
    await page.getByRole("button",{name:"从本条输入明确保存记忆"}).click();
    await page.locator("#chat-memory-content").fill("使用 Godot，先做桌面版"); await page.locator("#chat-memory-until").fill("2026-10-24T18:00"); await page.locator("#chat-memory-save-consent").check(); await page.locator("#chat-memory-save").click();
    await page.locator(".memory-pick").waitFor(); await page.locator(".memory-pick").check(); await page.locator("#chat-memory-preview").click();
    await page.locator("#chat-memory-outbound").waitFor({state:"visible"}); assert.ok((await page.locator("#chat-memory-outbound").innerText()).includes("使用 Godot"));
    await page.locator("#chat-memory-consent").check(); await page.locator("#chat-text").fill("参考本轮选定的项目背景"); await page.locator("#chat-send").click();
    await page.waitForFunction(()=>document.querySelectorAll(".chat-turn").length===2 && !document.querySelector("#chat-send").disabled);
    await page.getByText("本轮引用的记忆与来源",{exact:true}).click();
    assert.ok(await page.getByText("使用 Godot，先做桌面版",{exact:false}).count());
    assert.equal(await page.locator("#chat-memory-consent").isChecked(),false);
    await page.screenshot({path:input.desktop,fullPage:true});
    await page.reload(); await page.locator("#console").waitFor({state:"visible"});
    await page.locator("#chat-project").selectOption({label:"M6 演示"});
    await page.waitForFunction(()=>document.querySelectorAll(".chat-turn").length===2);
    await page.getByText("本轮记忆与明确保存",{exact:true}).click();
    await page.locator("#chat-memory-load").click(); await page.getByRole("button",{name:"修改并重新确认保存"}).click();
    assert.equal(await page.locator("#chat-memory-until").inputValue(),"2026-10-24T18:00");
    await page.locator("#chat-memory-content").fill("使用 Godot，先做 Windows 桌面版"); await page.locator("#chat-memory-save-consent").check(); await page.locator("#chat-memory-save").click();
    await page.waitForFunction(()=>document.querySelector("#chat-memory-choices").textContent.includes("Windows 桌面版"));
    await page.getByRole("button",{name:"撤销",exact:true}).click(); await page.getByText("当前项目没有有效记忆；聊天不会自动保存。",{exact:true}).waitFor();
    await page.locator('[data-tab="memories"]').click(); await page.locator("#project-workspace").selectOption({label:"M6 演示"});
    await page.locator("#project-todo-text").fill("先做可运行原型"); await page.locator('#project-todo-form button[type="submit"]').click();
    await page.locator("#project-todos article").waitFor(); await page.locator("#project-todos article select").first().selectOption("cancelled"); await page.getByRole("button",{name:"保存修改",exact:true}).click();
    await page.waitForFunction(()=>document.querySelector("#project-todos").textContent.includes("修订 2"));
    await page.getByRole("button",{name:"修改历史",exact:true}).click(); await page.locator("#project-todos pre").waitFor();
    assert.ok((await page.locator("#project-todos pre").innerText()).includes('"revision": 2'));
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"mobile horizontal overflow");
    await page.screenshot({path:input.mobile,fullPage:true});
    await page.locator('[data-tab="tasks"]').click(); await page.locator("#basic-tool").selectOption("preview_file_write");
    assert.equal(await page.locator("#basic-write-confirm").isEnabled(),false);
    await page.locator("#basic-content").fill("local-only draft"); await page.locator("#logout").click();
    await page.locator("#login-panel").waitFor({state:"visible"});
    assert.equal(await page.locator("#basic-content").inputValue(),"");
    assert.equal(await page.locator("#project-todos").innerText(),"");
    assert.deepEqual(errors,[]);
    process.stdout.write(JSON.stringify({passed:true,viewports:["1440x1000","390x844"],errors,real_model_calls:0}));
  } finally {await browser.close();}
}).on("error",error=>{console.error(error.message);process.exitCode=1;});
process.on("unhandledRejection",error=>{console.error(error.message);process.exitCode=1;});
